function strings(locale) {
  return TEXT[locale] || TEXT.en;
}

/**
 * Turn a { code, status } error into what the chat view shows.
 * Returns { text, retry: boolean, setup: boolean }.
 */
function describeError(error, locale) {
  const text = strings(locale);
  const code = error && typeof error.code === "string" ? error.code : "unexpected-error";
  if (code === "missing-secret") return { text: text.setupGuide, retry: false, setup: true };
  const key = code === "http-error" && error.status === 402 ? "insufficient-balance" : code;
  const message = Object.prototype.hasOwnProperty.call(text.errors, key) && text.errors[key] ? text.errors[key] : text.errors["unexpected-error"];
  const retry = Boolean(error && error.retryable) || ["invalid-response", "empty-response", "unexpected-error", "aborted"].includes(code);
  return { text: message, retry, setup: false };
}

